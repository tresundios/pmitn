                        <p>The word "Prison"—synonymous with 'Jail', 'Gaol', or 'Penitentiary'—is defined as a place properly arranged and equipped for the reception of persons who by legal process are committed to it for safe custody while awaiting trial or for punishment.</p>
                        
                        <p>During the period of the Sultanate, there were no regular Prisons. Only old forts and castles were used as prisons. During the time of Emperor Akbar, there were two kinds of prisons: one for criminals who had committed serious offences and another for ordinary criminals. Important nobles and princes guilty of treason and rebellions were imprisoned in fortresses situated in different parts of the country.</p>
                        
                        <p>The provision for proper jail buildings throughout India is the contribution of the British Government. The native Governments did not maintain proper jail buildings. Lord Macaulay, a member of the Indian Law Commission, initiated the Prison reform in 1835 for the first time in India. The Indian Prisons Act of 1894 regulated the prison system in the country. At that time, there were 43 civil, 75 criminal, and 68 mixed jails in India. These jails were run by District Magistrates.</p>
                        
                        <p>The Presidency Jail for women in Vellore was the first prison constructed in Tamil Nadu during the year 1830, followed by Madras "Penitentiary" during the year 1837, and thereafter all other prisons were constructed one by one up to the year 1872. After Independence, Central Prison, Puzhal was the only prison constructed during the year 1981, and some additional accommodation was made in other Prisons. All the Prison buildings are more than 150 years old. The Prisons play a vital role in the Administration of the Criminal Justice system and assist the courts in the due execution of the sentences awarded by them.</p>
